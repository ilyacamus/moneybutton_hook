LANGUAGE_NAMES = {"ru": "русском", "en": "английском", "uk": "украинском", "kk": "казахском"}


def language_line(language: str) -> str:
    name = LANGUAGE_NAMES.get(language, language)
    return f"Пиши все текстовые поля ответа на {name} языке."


